    It 'installs and removes the systemd timer through systemctl, and never touches the real one' {
        if (-not $IsLinux) { Skip-Test 'the systemd path is Linux-only; the other two are covered by their generators.' }
        $r = New-SubsRoot -Label 'subs-install'
        $savedXdg = $env:XDG_CONFIG_HOME
        try {
            $env:XDG_CONFIG_HOME = Join-Path $r.Root 'xdg'
            New-StubBinary -TestRoot $r -Name 'systemctl' -Behavior {
                $unit = Join-Path $env:XDG_CONFIG_HOME 'systemd/user/ytdl-subscriptions.timer'
                if ($StubArgs -contains 'is-active') { if (Test-Path -LiteralPath $unit) { Write-Output 'active'; exit 0 } else { Write-Output 'inactive'; exit 3 } }
                if ($StubArgs -contains 'show') { Write-Output 'NextElapseUSecRealtime=@1790006400'; exit 0 }
                exit 0
            } | Out-Null
            New-StubBinary -TestRoot $r -Name 'loginctl' -Behavior { Write-Output 'no'; exit 0 } | Out-Null

            $res = Invoke-Ytdl $r @('--schedule', 'install')
            Assert-Equal 0 $res.ExitCode ($res.Output -join "`n")
            $unitDir = Join-Path $env:XDG_CONFIG_HOME 'systemd/user'
            Assert-PathExists (Join-Path $unitDir 'ytdl-subscriptions.service')
            Assert-PathExists (Join-Path $unitDir 'ytdl-subscriptions.timer')
            Assert-FileMatches (Join-Path $unitDir 'ytdl-subscriptions.service') ([regex]::Escape((Join-Path $r.InstallRoot 'scripts/ytdl.ps1')))
            Assert-FileMatches (Join-Path $unitDir 'ytdl-subscriptions.service') 'YTDLP_INSTALL_ROOT=' 'a test install root is an override, and must be carried'
            $calls = @(Get-StubCalls -TestRoot $r -Name 'systemctl' | ForEach-Object { $_.line })
            Assert-True ($calls -contains '--user daemon-reload') "daemon-reload was not called: $($calls -join ' | ')"
            Assert-True ($calls -contains '--user enable --now ytdl-subscriptions.timer') "enable --now was not called: $($calls -join ' | ')"
            Assert-Match 'loginctl enable-linger' $res.Output 'with linger off, say that checks stop at logout'

            $st = ((Invoke-Ytdl $r @('--schedule', 'status', '--json')).Output -join "`n") | ConvertFrom-Json
            Assert-True $st.installed
            Assert-True $st.active
            Assert-Equal 1790006400 $st.next_check
            Assert-Equal $false $st.linger

            Clear-StubCalls -TestRoot $r
            $rm = Invoke-Ytdl $r @('--schedule', 'remove')
            Assert-Equal 0 $rm.ExitCode
            Assert-PathMissing (Join-Path $unitDir 'ytdl-subscriptions.timer')
            Assert-PathMissing (Join-Path $unitDir 'ytdl-subscriptions.service')
            $calls = @(Get-StubCalls -TestRoot $r -Name 'systemctl' | ForEach-Object { $_.line })
            Assert-True ($calls -contains '--user disable --now ytdl-subscriptions.timer') "disable --now was not called: $($calls -join ' | ')"
            Assert-Match 'nothing to remove' (Invoke-Ytdl $r @('--schedule', 'remove')).Output 'removing twice is not an error'


            Assert-PathMissing (Join-Path $unitDir 'ytdl-subscriptions.timer')
            Assert-Equal 0 @(Get-StubCalls -TestRoot $r -Name 'systemctl').Count
        } finally {
            $env:XDG_CONFIG_HOME = $savedXdg
            Remove-TestRoot $r
        }
    }

